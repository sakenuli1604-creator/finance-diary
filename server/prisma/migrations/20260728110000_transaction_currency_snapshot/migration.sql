-- AlterTable: добавляем колонку currency с временным дефолтом
ALTER TABLE "Transaction" ADD COLUMN "currency" TEXT NOT NULL DEFAULT '₸';

-- Backfill: проставляем валюту существующих транзакций по ТЕКУЩЕЙ валюте их счёта.
-- Важно: если валюта счёта уже была изменена задним числом (например, счёт был
-- в долларах, а потом его переключили на гривны), это НЕ восстановит исходную
-- валюту старых транзакций — этой информации нигде не сохранялось. Такие
-- конкретные записи придётся поправить вручную (отредактировать сумму транзакции).
-- Но начиная с этой миграции валюта транзакции больше не будет "плыть" при
-- смене валюты счёта в будущем — она фиксируется один раз в момент создания.
UPDATE "Transaction" t
SET "currency" = a."currency"
FROM "Account" a
WHERE t."accountId" = a."id";
